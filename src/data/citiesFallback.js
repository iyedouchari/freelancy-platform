/**
 * Normalise une chaîne de caractères pour la comparaison :
 * Suppression des accents, mise en minuscules, suppression de la ponctuation.
 */
export const normalizeLocationText = (str = "") => {
  return String(str || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
};

/**
 * Dictionnaire rapide des pays et leurs synonymes
 */
const COUNTRY_LOOKUP = (() => {
  const map = new Map();
  for (const c of WORLD_COUNTRIES) {
    const key = normalizeLocationText(c.city);
    map.set(key, c.country);
    if (Array.isArray(c.synonyms)) {
      for (const syn of c.synonyms) {
        map.set(normalizeLocationText(syn), c.country);
      }
    }
  }
  return map;
})();

/**
 * Détermine si une requête correspond à un pays connu.
 */
export const getMatchedCountry = (queryNorm) => {
  if (!queryNorm) return null;
  return COUNTRY_LOOKUP.get(queryNorm) || null;
};

/**
 * Score de pertinence unifié pour une localisation
 */
export const calculateLocationScore = (item, rawQuery) => {
  const q = normalizeLocationText(rawQuery);
  if (!q) {
    // Si vide : les 24 gouvernorats tunisiens sont prioritaires
    return item.isGovernorate ? 1000 : 0;
  }

  const c = normalizeLocationText(item.city);
  const s = normalizeLocationText(item.state);
  const co = normalizeLocationText(item.country);
  const cleanState = s.replace(/^gouvernorat (de l |de la |du |de )?/i, "").trim();

  const matchedCountry = getMatchedCountry(q);

  // ── CAS 1 : L'utilisateur recherche un PAYS (ex: "allemagne", "france", "tunisie", "canada") ──
  if (matchedCountry) {
    const targetCountryNorm = normalizeLocationText(matchedCountry);

    // Si le résultat est dans un PAYS COMPLÈTEMENT DIFFÉRENT (ex: Allemagne-en-Provence en France)
    // -> Bruit indésirable, on l'exclut immédiatement
    if (co !== targetCountryNorm) {
      return -1;
    }

    // Le pays lui-même en tête absolue (ex: Allemagne, Pays, Allemagne)
    if (item.isCountry && (c === targetCountryNorm || c === q)) {
      return 10000;
    }

    // Villes et gouvernorats du pays recherché
    if (c === q) return 8000;
    if (item.isGovernorate) return 6000;
    if (c.startsWith(q)) return 5500;
    return 5000;
  }

  // ── CAS 2 : L'utilisateur recherche une VILLE, GOUVERNORAT OU RÉGION (ex: "tunis", "medenine", "munich", "paris") ──

  const isTunisianGovName = TUNISIAN_GOVERNORATES.some(
    (g) => normalizeLocationText(g.city) === q
  );

  // Correspondance exacte sur la ville
  if (c === q) {
    if (item.isGovernorate) return 9500; // Ex: Tunis, Médenine, Béja, Sfax
    if (co === "tunisie") return 9000;
    if (item.isCountry) return 8500;
    if (isTunisianGovName && co !== "tunisie") {
      // Évite que des hameaux isolés à l'étranger (ex: Tunis en Virginie/Finlande) ne passent avant les délégations tunisiennes
      return 1500;
    }
    return 8000; // Ex: Munich, Paris, Berlin
  }

  // Ville commence exactement par la requête
  if (c.startsWith(q)) {
    if (item.isGovernorate) return 7500;
    return 6500;
  }

  // Correspondance exacte sur le nom du gouvernorat / région
  if (cleanState === q) {
    return 7000; // Ex: delegations sous le gouvernorat de Tunis (La Marsa, Carthage...)
  }

  if (cleanState.startsWith(q)) {
    return 5500;
  }

  // Ville contient le mot
  const cityWords = c.split(" ");
  if (cityWords.some((w) => w.startsWith(q))) {
    return 4500;
  }

  // État ou gouvernorat contient le mot
  if (s.includes(q)) {
    return 3500;
  }

  // Le pays commence par la requête (ex: "tun" pour "tunisie")
  if (co.startsWith(q) && q.length >= 3) {
    if (item.isCountry) return 4000;
    if (item.isGovernorate) return 3000;
    return 2000;
  }

  return -1;
};

/**
 * Trie, déduplique et classe une liste d'éléments selon leur pertinence
 */
export const rankLocations = (items, query) => {
  const q = String(query || "").trim();
  const scored = [];
  const seen = new Set();

  for (const item of items) {
    const score = calculateLocationScore(item, q);
    if (score > 0) {
      // Clé unique pour dédupliquer (ex: "paris|france", "tunis|tunisie")
      const key = `${normalizeLocationText(item.city)}|${normalizeLocationText(item.country)}`;
      if (!seen.has(key)) {
        seen.add(key);
        scored.push({ item, score });
      }
    }
  }

  // Tri décroissant par score
  scored.sort((a, b) => b.score - a.score);

  return scored.map((s) => s.item);
};

/**
 * Recherche instantanée dans le jeu de données local fallback
 */
export const searchFallbackCities = (query = "") => {
  const q = String(query || "").trim();
  if (!q) {
    // Si aucun texte : les 24 gouvernorats tunisiens sont retournés immédiatement dans l'ordre officiel
    return TUNISIAN_GOVERNORATES;
  }

  const ranked = rankLocations(REAL_CITIES, q);
  return ranked.slice(0, 24);
};
