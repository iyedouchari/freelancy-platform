export const searchFallbackCities = (query) => {
  if (!query || query.trim().length < 1) return [];
  const normalized = query
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");

  return REAL_CITIES.filter((item) => {
    const cityName = item.city.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
    const stateName = (item.state || "").toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
    const countryName = item.country.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");

    return (
      cityName.includes(normalized) ||
      stateName.includes(normalized) ||
      countryName.includes(normalized)
    );
  }).slice(0, 10);
};
